// Generates contracts/mochi.css from docs/design-system/tokens.json. Never edit mochi.css by hand.
// Usage: node contracts/gen-css.ts          (write)
//        node contracts/gen-css.ts --check  (exit 1 if mochi.css is stale)
import { readFileSync, writeFileSync } from 'node:fs';

type Token = { name: string; value: string | Record<string, string> };
type Style = { name: string; family: string; fontSize: string; lineHeight: string; fontWeight: number | string; letterSpacing?: string; fontStyle?: string };
type Tokens = {
  color: { themes: { id: string }[]; tokens: Token[] };
  type: { families: Record<string, string>; groups: { styles: Style[] }[] };
  [family: string]: any;
};

const TOKENS = new URL('../docs/design-system/tokens.json', import.meta.url);
const OUT = new URL('./mochi.css', import.meta.url);
const FONTS = 'https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500&family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&family=Instrument+Serif:ital@0;1&display=swap';
const NON_COLOR = ['spacing', 'radius', 'shadow', 'layout', 'shape'];

export const cssVar = (name: string) => `--${name.replace(/\./g, '\\.')}`;

export function generate(t: Tokens): string {
  const [first, ...rest] = t.color.themes.map((x) => x.id);
  const colorFor = (theme: string) => t.color.tokens.map((tok) => {
    const v = typeof tok.value === 'string' ? tok.value : tok.value[theme] ?? tok.value[first];
    return `  ${cssVar(tok.name)}: ${v};`;
  });
  const block = (sel: string, lines: string[], indent = '') => `${indent}${sel} {\n${lines.map((l) => indent + l).join('\n')}\n${indent}}`;

  const rootLines = [
    `  color-scheme: light;`,
    ...Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`),
    ...NON_COLOR.flatMap((fam) => (t[fam]?.tokens ?? []).map((tok: Token) => `  ${cssVar(tok.name)}: ${tok.value};`)),
    ...colorFor(first),
  ];
  const out = [
    '/* GENERATED by contracts/gen-css.ts from docs/design-system/tokens.json. Do not edit. */',
    `@import url('${FONTS}');`,
    block(':root', rootLines),
  ];
  for (const theme of rest) {
    const lines = [`  color-scheme: ${theme === 'dark' ? 'dark' : 'light'};`, ...colorFor(theme)];
    out.push(block(`:root[data-theme="${theme}"]`, lines));
    if (theme === 'dark') out.push(`@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', lines, '  ')}\n}`);
  }
  for (const s of t.type.groups.flatMap((g) => g.styles)) {
    const decl = [
      `  font-family: var(--font-${s.family});`, `  font-size: ${s.fontSize};`,
      `  line-height: ${s.lineHeight};`, `  font-weight: ${s.fontWeight};`,
      ...(s.letterSpacing ? [`  letter-spacing: ${s.letterSpacing};`] : []),
      ...(s.fontStyle ? [`  font-style: ${s.fontStyle};`] : []),
    ];
    out.push(block(`.t-${s.name}`, decl));
  }
  out.push(`@media (prefers-reduced-motion: reduce) {\n  *, *::before, *::after {\n    animation-duration: 0.01ms !important;\n    animation-iteration-count: 1 !important;\n    transition-duration: 0.01ms !important;\n    scroll-behavior: auto !important;\n  }\n}`);
  return out.join('\n\n') + '\n';
}

if (import.meta.main) {
  const css = generate(JSON.parse(readFileSync(TOKENS, 'utf8')));
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch {}
    if (current !== css) { console.error('contracts/mochi.css is stale or hand-edited: run node contracts/gen-css.ts'); process.exit(1); }
  } else writeFileSync(OUT, css);
}
